import os
import sys
import shutil
import subprocess
from pathlib import Path
from typing import Tuple
import fitz  # PyMuPDF
from PIL import Image
import pytesseract
from app.config import settings

WIN_OCR_SCRIPT = os.path.join(os.path.dirname(__file__), "win_ocr.ps1")

# Configure Tesseract path if specified or if found
if settings.TESSERACT_CMD and os.path.exists(settings.TESSERACT_CMD):
    pytesseract.pytesseract.tesseract_cmd = settings.TESSERACT_CMD
else:
    common_paths = [
        r"C:\Program Files\Tesseract-OCR\tesseract.exe",
        r"C:\Program Files (x86)\Tesseract-OCR\tesseract.exe",
        os.path.expandvars(r"%LOCALAPPDATA%\Programs\Tesseract-OCR\tesseract.exe"),
    ]
    for path in common_paths:
        if os.path.exists(path):
            pytesseract.pytesseract.tesseract_cmd = path
            break

def is_tesseract_available() -> bool:
    """Check whether Tesseract executable is installed and operable."""
    try:
        cmd = pytesseract.pytesseract.tesseract_cmd
        if cmd and os.path.exists(cmd):
            return True
        return shutil.which("tesseract") is not None
    except Exception:
        return False

def is_ocr_available() -> bool:
    """Check whether either Tesseract or Windows Native OCR is available."""
    if is_tesseract_available():
        return True
    if sys.platform == "win32" and os.path.exists(WIN_OCR_SCRIPT):
        return True
    return False

def extract_with_windows_ocr(image_path: str) -> str:
    """Invokes Windows Native Media OCR with coordinate-based line reconstruction."""
    if not os.path.exists(WIN_OCR_SCRIPT):
        return ""
    try:
        cmd = [
            "powershell",
            "-NoProfile",
            "-ExecutionPolicy",
            "Bypass",
            "-File",
            WIN_OCR_SCRIPT,
            "-ImagePath",
            os.path.abspath(image_path)
        ]
        res = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
        if res.returncode == 0 and res.stdout.strip():
            return res.stdout.strip()
    except Exception as e:
        print(f"[Windows OCR Error] {e}")
    return ""

def extract_from_image(image_path: str) -> str:
    """Extracts text from an image file (PNG, JPG) using Windows Native OCR or Tesseract with auto-preprocessing."""
    prep_path = None
    target_path = image_path
    try:
        with Image.open(image_path) as im:
            needs_prep = False
            if im.mode == "RGBA":
                bg = Image.new("RGB", im.size, (255, 255, 255))
                bg.paste(im, mask=im.split()[3])
                im = bg
                needs_prep = True
            elif im.mode != "RGB":
                im = im.convert("RGB")
                needs_prep = True
            
            w, h = im.size
            if w < 1600 or h < 1600:
                scale = 2
                im = im.resize((w * scale, h * scale), Image.Resampling.LANCZOS)
                needs_prep = True
            
            if needs_prep:
                prep_path = f"{image_path}_prep_ocr.png"
                im.save(prep_path)
                target_path = prep_path
    except Exception as e:
        print(f"[Image Preprocessing Warning] {e}")

    try:
        # 1. Try Windows native OCR first on Windows (built-in to OS)
        if sys.platform == "win32":
            win_text = extract_with_windows_ocr(target_path)
            if win_text and len(win_text) > 20:
                return win_text

        # 2. Try Tesseract
        if is_tesseract_available():
            try:
                with Image.open(target_path) as img:
                    gray = img.convert("L")
                    text = pytesseract.image_to_string(gray)
                    if text.strip():
                        return text.strip()
            except Exception as e:
                print(f"[Tesseract OCR Error] {e}")
    finally:
        if prep_path and os.path.exists(prep_path):
            try:
                os.remove(prep_path)
            except Exception:
                pass

    return (
        "[NOTICE: The uploaded file is an image and no operational OCR engine could be found on this server. "
        "Please upload digital PDF medical reports directly generated by laboratory software.]"
    )

def extract_from_pdf(pdf_path: str) -> Tuple[str, bool]:
    """
    Extracts text from a PDF file using PyMuPDF (digital) first.
    If the document has low or no text (scanned), attempts OCR via Windows OCR or Tesseract.
    Returns (extracted_text, is_scanned).
    """
    doc = fitz.open(pdf_path)
    full_text = []
    
    for page_num in range(len(doc)):
        page = doc[page_num]
        text = page.get_text("text")
        if text.strip():
            full_text.append(text)
    
    combined = "\n".join(full_text).strip()
    
    # If substantial text was extracted, treat as digital PDF
    if len(combined) > 60:
        doc.close()
        return combined, False

    # Scanned PDF fallback
    if not is_ocr_available():
        doc.close()
        return (
            combined or 
            "[NOTICE: Document appears to be a scanned image-based PDF. OCR engine is not configured on this server. "
            "For scanned document support, please upload digital PDFs generated directly by laboratory software.]",
            True
        )

    # If OCR is available, render pages to images and run extraction
    ocr_text = []
    for page_num in range(len(doc)):
        page = doc[page_num]
        pix = page.get_pixmap(dpi=200)
        img_path = f"{pdf_path}_page_{page_num}.png"
        pix.save(img_path)
        try:
            txt = extract_from_image(img_path)
            if txt.strip() and not txt.startswith("[NOTICE:"):
                ocr_text.append(txt)
        finally:
            if os.path.exists(img_path):
                os.remove(img_path)

    doc.close()
    result = "\n".join(ocr_text).strip()
    return result if result else combined, True

def extract_text(file_path: str) -> Tuple[str, bool]:
    """
    Unified extractor for supported file types.
    Returns (extracted_text, is_scanned_or_image).
    """
    ext = Path(file_path).suffix.lower()
    if ext == ".pdf":
        return extract_from_pdf(file_path)
    elif ext in [".png", ".jpg", ".jpeg"]:
        return extract_from_image(file_path), True
    else:
        raise ValueError(f"Unsupported file format: {ext}")
